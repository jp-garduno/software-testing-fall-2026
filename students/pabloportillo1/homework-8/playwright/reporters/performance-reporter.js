const fs = require("node:fs");
const path = require("node:path");

const OUTPUT = path.resolve(__dirname, "..", "..", "PERFORMANCE_REPORT.md");
const METRICS = [
  ["pageLoad", "Page load (navigate until the input is visible)"],
  ["domContentLoaded", "DOMContentLoaded (Navigation Timing)"],
  ["loadEvent", "Load event end (Navigation Timing)"],
  ["addOne", "Add 1 todo"],
  ["addBulk", "Add 50 todos"],
  ["toggleAll", "Toggle all 51 todos"],
  ["filterSwitch", "Switch to the Active filter"],
  ["clearCompleted", "Clear 51 completed todos"],
];

/** Collects the "performance" attachments of a run and writes PERFORMANCE_REPORT.md at the homework root. */
class PerformanceReporter {
  constructor() {
    this.results = [];
  }

  onTestEnd(test, result) {
    const attachment = result.attachments.find((item) => item.name === "performance");
    if (attachment) {
      this.results.push({ ...JSON.parse(attachment.body.toString()), status: result.status });
    }
  }

  onEnd() {
    if (this.results.length === 0) {
      return;
    }
    const results = [...this.results].sort((a, b) => a.browser.localeCompare(b.browser));
    const header = `| Metric (median ms) | ${results.map((r) => r.browser).join(" | ")} |`;
    const divider = `| --- | ${results.map(() => "---:").join(" | ")} |`;
    const rows = METRICS.map(
      ([key, label]) => `| ${label} | ${results.map((r) => r.medians[key].toFixed(0)).join(" | ")} |`,
    );
    const budgets = `| Within budget | ${results.map((r) => (r.status === "passed" ? "yes" : "no")).join(" | ")} |`;
    const { runs, bulkSize } = results[0];
    const report = [
      "# Performance Report",
      "",
      `Generated by \`npm run test:performance\` on ${new Date().toLocaleDateString("en-CA")}.`,
      "",
      `Each browser loads the app ${runs} times, each time in a new browser context, so every load is a first`,
      `visit with an empty cache. Every metric is the median of the ${runs} runs. Operation times are measured from`,
      "the test, so they include Playwright's own round trips to the browser, the same way a user waits for them.",
      `The bulk step adds ${bulkSize} todos one by one through the input.`,
      "",
      header,
      divider,
      ...rows,
      budgets,
      "",
      "Budgets: page load under 5000 ms, adding 50 todos under 15000 ms.",
      "",
    ].join("\n");
    fs.writeFileSync(OUTPUT, report);
  }
}

module.exports = PerformanceReporter;
