"""Bonus C: performance metrics with Selenium.

Page load. The app is loaded several times in a brand-new browser profile, so the first load starts
with an empty cache and the rest reuse it. Each load is read from the browser's Navigation Timing API
and is also timed from the test (from driver.get until the input accepts text), which includes
WebDriver's own overhead and is closer to what a user waits for.

Operations. Each user action is timed several times, always from the same starting state (a freshly
loaded app plus whatever the action needs). The time includes the page object's explicit wait for the
visible effect of the action, so it stops when the user can see the result.

Every run rewrites PERFORMANCE_REPORT.md. The tests fail only when a median goes over its budget.
"""

import statistics
import sys
import time
from datetime import datetime
from pathlib import Path

import markdown_report
import pytest
from firefox_driver import start_firefox, window_visible
from pages.todo_page import TodoPage

REPORT = Path(__file__).resolve().parent.parent / "PERFORMANCE_REPORT.md"
LOADS = 5
REPETITIONS = 5
LOAD_BUDGET_MS = 5000  # median of the load event
OPERATION_BUDGET_MS = 1000  # median of each operation

NAVIGATION_TIMING = """
const entry = performance.getEntriesByType("navigation")[0];
return [entry.responseStart, entry.domContentLoadedEventEnd, entry.loadEventEnd];
"""
LOAD_METRICS = ("Time to first byte", "DOM content loaded", "Load event", "App ready (timed by the test)")


def add_one(todo_page):
    todo_page.add_todo("Existing task")


def add_one_completed(todo_page):
    add_one(todo_page)
    todo_page.toggle_todo(0)


def add_mixed_list(todo_page):
    todo_page.add_todos("Task 1", "Task 2", "Task 3")
    todo_page.toggle_todo(1)


def edit_first(todo_page):
    todo_page.start_editing(0)
    todo_page.type_edit("Edited task")
    todo_page.confirm_edit()


# operation name -> (prepare the starting state, the action being timed)
OPERATIONS = {
    "Add a todo": (lambda todo_page: None, lambda todo_page: todo_page.add_todo("New task")),
    "Complete a todo": (add_one, lambda todo_page: todo_page.toggle_todo(0)),
    "Edit a todo": (add_one, edit_first),
    "Delete a todo": (add_one, lambda todo_page: todo_page.delete_todo(0)),
    "Filter by Active": (add_mixed_list, lambda todo_page: todo_page.filter_active()),
    "Clear completed": (add_one_completed, lambda todo_page: todo_page.clear_completed()),
}


def milliseconds(value):
    return f"{value:.0f} ms"


def write_report(results):
    mode = "visible window" if window_visible() else "headless"
    lines = [
        "# Performance Report",
        "",
        f"Generated by `tests/test_performance.py` on {datetime.now():%Y-%m-%d %H:%M} against the live site "
        f"({results['browser']}, {mode}, `{sys.platform}`).",
    ]
    if results["loads"]:
        loads, later = results["loads"], results["loads"][1:]
        rows = [
            (metric, milliseconds(loads[0][metric]), milliseconds(statistics.median(load[metric] for load in later)))
            for metric in LOAD_METRICS
        ]
        lines += [
            "",
            "## Page Load",
            "",
            f"The app was loaded {LOADS} times in a new browser profile, so only the first load had an empty cache.",
            "",
            *markdown_report.table(("Metric", "First load", f"Median of the other {LOADS - 1}"), rows),
        ]
    if results["operations"]:
        rows = [
            (name, milliseconds(statistics.median(times)), milliseconds(min(times)), milliseconds(max(times)))
            for name, times in results["operations"].items()
        ]
        lines += [
            "",
            "## Operations",
            "",
            f"Each action was timed {REPETITIONS} times from the same starting state, until its effect was visible.",
            "",
            *markdown_report.table(("Operation", "Median", "Fastest", "Slowest"), rows),
        ]
    lines += [
        "",
        f"The tests fail when the median load event goes over {LOAD_BUDGET_MS} ms or the median of an operation "
        f"goes over {OPERATION_BUDGET_MS} ms.",
    ]
    markdown_report.write(REPORT, lines)


@pytest.fixture(name="results", scope="module")
def fixture_results(driver):
    """Collects every measurement and writes the report once all the tests in this file ran."""
    results = {"browser": f"{driver.capabilities['browserName']} {driver.capabilities['browserVersion']}"}
    results.update(loads=[], operations={})
    yield results
    write_report(results)


@pytest.fixture(name="new_profile_driver")
def fixture_new_profile_driver():
    """A browser of its own, so the first load cannot reuse a cache filled by another test."""
    driver = start_firefox()
    yield driver
    driver.quit()


def test_page_load_time(new_profile_driver, results):
    todo_page = TodoPage(new_profile_driver)

    for _ in range(LOADS):
        started = time.perf_counter()
        todo_page.navigate()
        ready = (time.perf_counter() - started) * 1000
        first_byte, dom_loaded, load_event = new_profile_driver.execute_script(NAVIGATION_TIMING)
        results["loads"].append(dict(zip(LOAD_METRICS, (first_byte, dom_loaded, load_event, ready))))

    median_load = statistics.median(load["Load event"] for load in results["loads"])
    assert median_load <= LOAD_BUDGET_MS, f"Median load event took {median_load:.0f} ms"


@pytest.mark.parametrize("operation", OPERATIONS)
def test_operation_time(operation, todo_page, results):
    prepare, action = OPERATIONS[operation]
    times = []

    for _ in range(REPETITIONS):
        todo_page.navigate()
        prepare(todo_page)
        started = time.perf_counter()
        action(todo_page)
        times.append((time.perf_counter() - started) * 1000)
    results["operations"][operation] = times

    median_time = statistics.median(times)
    assert median_time <= OPERATION_BUDGET_MS, f"{operation} took {median_time:.0f} ms (median)"
